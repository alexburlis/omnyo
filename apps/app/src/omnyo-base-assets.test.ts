import {
  cp,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  symlink,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, expect, it } from "vitest";
import sharp from "sharp";
import { exportOmnyoBaseAssets } from "../scripts/export-omnyo-base-assets.mjs";

const roots: string[] = [];

const repoRoot = resolve(import.meta.dirname, "../../..");

afterEach(async () => {
  for (const root of roots.splice(0))
    await rm(root, { recursive: true, force: true });
});

async function fixture() {
  const root = await mkdtemp(join(tmpdir(), "omnyo-assets-"));
  roots.push(root);
  await mkdir(join(root, "assets/omnyo"), { recursive: true });
  await cp(
    join(repoRoot, "assets/omnyo/mark.svg"),
    join(root, "assets/omnyo/mark.svg"),
  );
  await cp(
    join(repoRoot, "assets/omnyo/exports.json"),
    join(root, "assets/omnyo/exports.json"),
  );

  return root;
}

it("exports opaque light icons, transparent dark icons, and adaptive safe-area geometry", async () => {
  const root = await fixture();
  await exportOmnyoBaseAssets({ root, selectedFamilies: ["mobile"] });

  const light = await sharp(
    join(root, "apps/mobile/assets/icon.png"),
  ).metadata();

  const dark = await sharp(
    join(root, "apps/mobile/assets/ios-icon-dark.png"),
  ).metadata();

  expect([light.width, light.height, light.hasAlpha]).toEqual([
    1024,
    1024,
    false,
  ]);
  expect([dark.width, dark.height, dark.hasAlpha]).toEqual([1024, 1024, true]);

  const { data, info } = await sharp(
    join(root, "apps/mobile/assets/android-icon-foreground.png"),
  )
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const satellitePixel = (383 * info.width + 640) * 4;
  expect([...data.subarray(satellitePixel, satellitePixel + 4)]).toEqual([
    255, 79, 23, 255,
  ]);

  const monochrome = await sharp(
    join(root, "apps/mobile/assets/android-icon-monochrome.png"),
  )
    .extract({ left: 640, top: 383, width: 1, height: 1 })
    .raw()
    .toBuffer();

  expect([...monochrome]).toEqual([250, 249, 246, 255]);

  let min = 1024;
  let max = 0;

  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 0) {
        min = Math.min(min, x, y);
        max = Math.max(max, x, y);
      }
    }

  expect(min).toBeGreaterThan(270);
  expect(max).toBeLessThan(754);
  expect(max - min).toBeGreaterThan(300);
});

it("detects changed generated bytes without writing during check and regenerates deterministically", async () => {
  const root = await fixture();
  const first = await exportOmnyoBaseAssets({ root });
  const file = join(root, "apps/app/public/icon-192.png");
  const original = await readFile(file);
  await writeFile(file, "corrupted owned icon");
  await expect(
    exportOmnyoBaseAssets({ root, checkOnly: true }),
  ).rejects.toThrow("icon-192.png");
  expect(await readFile(file, "utf8")).toBe("corrupted owned icon");
  await exportOmnyoBaseAssets({ root });
  expect(await readFile(file)).toEqual(original);
  const checked = await exportOmnyoBaseAssets({ root, checkOnly: true });
  expect(
    checked.records.map(({ sha256 }: { sha256: string }) => sha256),
  ).toEqual(first.records.map(({ sha256 }: { sha256: string }) => sha256));
});

it("refuses an escaped or symlinked target before writing any artwork", async () => {
  const root = await fixture();
  const manifestPath = join(root, "assets/omnyo/exports.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.outputs[1].path = "../foreign.png";
  await writeFile(manifestPath, JSON.stringify(manifest));
  await expect(exportOmnyoBaseAssets({ root })).rejects.toThrow(
    "escapes source",
  );
  await expect(
    readFile(join(root, manifest.outputs[0].path)),
  ).rejects.toMatchObject({ code: "ENOENT" });
  manifest.outputs[1].path = "linked/icon.png";
  await writeFile(manifestPath, JSON.stringify(manifest));
  await symlink(join(root, "assets"), join(root, "linked"));
  await expect(exportOmnyoBaseAssets({ root })).rejects.toThrow(
    "not owned source",
  );
});
